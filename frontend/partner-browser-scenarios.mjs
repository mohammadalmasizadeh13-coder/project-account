import assert from 'node:assert/strict';

export async function checkPartnerDocuments({ cdp, evaluate, ready, until, go, fill, click, resize, screenshot, workspace }) {
  await cdp('Page.enable'); await cdp('Runtime.enable');
  await cdp('Fetch.enable', { patterns: [{ urlPattern: '*fonts.googleapis.com*' }, { urlPattern: '*fonts.gstatic.com*' }] });
  await resize(1440);
  await go('/register'); await ready('#account-password-confirmation');
  await until(`!document.querySelector('.accounting-submit').disabled`);
  await fill('#account-username', 'partner-documents');
  await fill('#account-gallery-name', 'گالری اسناد همکاران');
  await fill('#account-password', 'partner-browser-test-password');
  await fill('#account-password-confirmation', 'partner-browser-test-password');
  await click('.accounting-submit'); await ready('.workspace-page');
  const open = async type => {
    if (await evaluate(`document.querySelector('.workspace-rail')?.getAttribute('aria-hidden') === 'true'`)) await click('.workspace-menu-toggle');
    await click('[data-section="entries"]');
    await click(`[data-tool="${type}"]`);
    await ready('[data-partner-select]');
    assert.equal(await evaluate(`document.querySelector('[data-document-type]').value`), type);
  };
  await open('partner-remittance');
  await click('[data-partner-new]');
  await fill('[data-partner-profile] [name="name"]', 'همکار آزمایش حواله');
  await click('[data-partner-save]');
  await ready('[data-partner-settlement-form]');
  const success = () => until(`document.querySelector('.partner-crm .form-message.success')`);
  const standaloneRemittances = [];
  for (const [direction, balance] of [['debit', 10], ['credit', 0]]) {
    await fill('[data-partner-settlement-form] [name="direction"]', direction);
    await fill('[data-partner-settlement-form] [name="goldAmount"]', '۱۰');
    await fill('[data-partner-settlement-form] [name="reference"]', `حواله ${direction}`);
    await click('[data-partner-payment-save]'); await success();
    const saved = await workspace();
    assert.equal(saved.data.partners[0].goldBalance, balance);
    const remittance = saved.data.partners[0].entries.at(-1);
    assert.equal(remittance.paymentMethod, 'remittance');
    assert.ok(Number.isSafeInteger(remittance.invoiceNumber) && remittance.invoiceNumber > 0);
    assert.ok(remittance.transactionId);
    assert.equal(remittance.documentIds.length, 0);
    standaloneRemittances.push(remittance);
    assert.equal(saved.data.documents.length, 0);
  }
  assert.equal(new Set(standaloneRemittances.map(entry => entry.invoiceNumber)).size, 2);
  assert.equal(new Set(standaloneRemittances.map(entry => entry.transactionId)).size, 2);
  await fill('[data-partner-settlement-form] [name="goldAmount"]', '۷');
  await go('/account'); await ready('.workspace-page'); await open('partner-remittance');
  assert.equal(await evaluate(`document.querySelector('[name="goldAmount"]').value`), '7');
  await resize(390, 844);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), true);
  await screenshot('partner-remittance-mobile', '[data-partner-document-entry]');
  await resize(1440);
  const buy = async (category, values) => {
    await open(`partner-${category}-purchase`);
    for (const [name, value] of Object.entries({ gold18Price: '100000', ...values })) await fill(`[data-partner-invoice] [name="${name}"]`, value);
    await click('[data-partner-invoice-save]'); await success();
    return (await workspace()).data.documents[0];
  };
  const crafted = await buy('crafted', { itemName: 'انگشتر همکار', itemCount: '۳', weight: '۶', ayar: '۷۵۰', wagePercent: '۰', profitPercent: '۰' });
  const coin = await buy('coin', { itemName: 'سکه همکار', coinCount: '۳', coinPrice: '۲۰۰۰۰۰', profitPercent: '۰' });
  assert.equal((await workspace()).data.partners[0].goldBalance, 12);
  for (const [category, stock] of [['crafted', crafted], ['coin', coin]]) {
    await open(`partner-${category}-sale`);
    await fill('[data-partner-invoice] [name="gold18Price"]', '100000');
    await fill('[data-partner-invoice] [name="inventorySourceId"]', stock.id);
    await fill('[data-partner-invoice] [name="profitPercent"]', '۰');
    if (category === 'coin') await fill('[data-partner-invoice] [name="coinPrice"]', '200000');
    if (category === 'crafted') {
      assert.equal(await evaluate(`document.querySelector('[data-partner-line] [name="weight"]').readOnly`), true);
      // Drafts must not mix the purchase and sale of the same category.
      await fill('[data-document-type]', 'partner-crafted-purchase');
      assert.equal(await evaluate(`document.querySelector('[data-partner-line] [name="itemName"]').value`), '');
      await fill('[data-document-type]', 'partner-crafted-sale');
      assert.equal(await evaluate(`document.querySelector('[name="inventorySourceId"]').value`), stock.id);
    }
    await click('[data-partner-invoice-save]'); await success();
    const saved = await workspace();
    assert.equal(saved.data.documents[0].type, `${category}-sale`);
    assert.equal(saved.data.documents[0].inventorySourceId, stock.id);
    assert.equal(saved.data.partners[0].entries.at(-1).goldCredit, 2);
  }
  assert.equal((await workspace()).data.partners[0].goldBalance, 8);
  await go('/account'); await ready('.workspace-page');
  assert.equal((await workspace()).data.partners[0].goldBalance, 8);
  await open('partner-remittance');
  assert.equal(await evaluate(`document.querySelector('[name="goldAmount"]').value`), '7');

  // A fee quoted for melted gold is independent from the per-gram conversion rate.
  await click('[data-section="entries"]'); await click('[data-tool="pricing"]');
  await fill('.price-form [name="goldGramPrice"]', '۲۰۰۰۰۰۰۰');
  await fill('.price-form [name="meltedFee"]', '۱۰۰۰۰۰۰۰۰');
  await click('.price-form button[type="submit"]');
  await until(`document.querySelector('.noor-save-state')?.textContent.includes('اطلاعات در سرور ذخیره است.')`);
  await go('/account'); await ready('.workspace-page');
  assert.equal((await workspace()).data.prices.goldGramPrice, '20000000');
  assert.equal((await workspace()).data.prices.meltedFee, '100000000');
  await click('[data-section="reports"]'); await click('[data-tool="rates"]');
  assert.equal(await evaluate(`document.querySelector('.rate-cards').textContent.includes('فی آب‌شده')`), true);

  const beforeMixed = (await workspace()).data;
  await open('partner-crafted-purchase');
  const setRow = async (index, values) => {
    for (const [name, value] of Object.entries(values)) await fill(`[data-partner-line="${index}"] [name="${name}"]`, value);
  };
  await fill('[data-partner-invoice] [name="gold18Price"]', '20000000');
  await fill('[data-partner-invoice] [name="externalInvoiceNumber"]', 'MIXED-110');
  await setRow(0, { category: 'crafted', direction: 'purchase', itemName: 'کار ساخته سند ترکیبی', itemCount: '۱', weight: '۱۰', ayar: '۷۵۰', wagePercent: '۰', profitPercent: '۰' });
  await click('[data-partner-add-line]');
  await setRow(1, { category: 'coin', direction: 'sale', inventorySourceId: coin.id, coinCount: '۲', coinPrice: '۲۰۰۰۰۰', profitPercent: '۰' });
  await click('[data-partner-add-line]');
  await setRow(2, { category: 'remittance', remittanceDirection: 'credit', goldAmount: '۱۰', reference: 'حواله همین سند' });
  await click('[data-partner-add-line]');
  await setRow(3, { category: 'melted', direction: 'purchase' });
  assert.equal(await evaluate(`document.querySelector('[data-partner-line="3"] [name="meltedFee"]').value.replaceAll(',', '')`), '100000000');
  await setRow(3, { itemName: 'آب‌شده سند ترکیبی', itemCount: '۱', meltedWeight: '۲۰', meltedAyar: '۷۵۰', meltedFee: '۱۱۰۰۰۰۰۰۰', wagePercent: '۰', profitPercent: '۰', assayCode: '110', laboratoryName: 'آزمایشگاه سند ترکیبی' });
  const numericText = selector => evaluate(`Number(document.querySelector(${JSON.stringify(selector)}).textContent.replace(/[۰-۹]/g, digit => '۰۱۲۳۴۵۶۷۸۹'.indexOf(digit)).replace(/٫/g, '.').replace(/[^0-9.]/g, ''))`);
  const expectedMeltedAmount = 110000000 / 4.3318 * 20;
  assert.ok(Math.abs(await numericText('[data-partner-line="3"] [data-partner-line-amount]') - expectedMeltedAmount) < 0.01);
  assert.ok(Math.abs(await numericText('[data-partner-line="3"] [data-partner-melted-gram-price]') - 110000000 / 4.3318) < 0.01);
  // All four independent row kinds and directions survive a draft reload.
  await go('/account'); await ready('.workspace-page'); await open('partner-crafted-purchase');
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('[data-partner-line] [name="category"]'), input => input.value)`), ['crafted', 'coin', 'remittance', 'melted']);
  assert.equal(await evaluate(`document.querySelector('[data-partner-line="1"] [name="direction"]').value`), 'sale');
  assert.equal(await evaluate(`document.querySelector('[data-partner-line="3"] [name="meltedFee"]').value.replaceAll(',', '')`), '110000000');
  await resize(390, 844);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), true);
  await screenshot('partner-mixed-invoice-mobile', '[data-partner-document-entry]');
  await resize(1440);
  await click('[data-partner-invoice-save]'); await success();
  const afterMixed = (await workspace()).data;
  const entry = afterMixed.partners[0].entries.at(-1);
  const round = value => Math.round(value * 1e6) / 1e6;
  assert.equal(afterMixed.partners[0].entries.length, beforeMixed.partners[0].entries.length + 1);
  assert.equal(afterMixed.documents.length, beforeMixed.documents.length + 3);
  assert.equal(entry.calculationVersion, 3);
  assert.equal(entry.lines.length, 4);
  assert.equal(entry.documentIds.length, 3);
  assert.equal(entry.goldDebit, round(10 + expectedMeltedAmount / 20000000));
  assert.equal(entry.goldCredit, 10.02);
  assert.equal(afterMixed.partners[0].goldBalance, round(beforeMixed.partners[0].goldBalance + entry.goldDebit - entry.goldCredit));
  assert.equal(entry.lines[2].category, 'remittance');
  assert.equal(entry.lines[2].goldCredit, 10);
  assert.ok(!entry.lines[2].documentId);
  assert.equal(entry.lines[3].meltedFee, 110000000);
  assert.ok(Math.abs(entry.lines[3].amount - expectedMeltedAmount) < 0.01);
  const linked = entry.documentIds.map(id => afterMixed.documents.find(doc => doc.id === id));
  assert.deepEqual(linked.map(doc => doc.type).sort(), ['coin-sale', 'crafted-purchase', 'melted-purchase']);
  assert.equal(linked.find(doc => doc.type === 'coin-sale').inventorySourceId, coin.id);
  assert.equal(new Set(linked.map(doc => doc.transactionId)).size, 1);
  assert.equal(new Set(linked.map(doc => doc.invoiceNumber)).size, 1);
  assert.ok(Math.abs(linked.find(doc => doc.category === 'melted').amount - expectedMeltedAmount) < 0.01);
  await go('/account'); await ready('.workspace-page');
  const reloaded = (await workspace()).data;
  assert.deepEqual(reloaded.partners[0].entries.at(-1), entry);
  assert.equal(reloaded.partners[0].goldBalance, afterMixed.partners[0].goldBalance);
  assert.deepEqual(entry.documentIds.map(id => reloaded.documents.find(doc => doc.id === id)), linked);
  await click('[data-section="reports"]'); await click('[data-tool="search"]');
  const mixedCard = `[data-invoice-id="${entry.transactionId}"]`;
  await ready(mixedCard);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(mixedCard)}).textContent.includes('حواله')`), true);
  await click(`${mixedCard} [data-invoice-view]`); await ready('[data-partner-document-dialog]');
  assert.equal(await evaluate(`document.querySelector('[data-partner-document-dialog]').textContent.includes('فی آب‌شده')`), true);
  await resize(390, 844);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), true);
  await screenshot('partner-mixed-document-mobile', '[data-partner-document-dialog]');
  await click('[data-partner-document-close]'); await resize(1440);
  await click(`${mixedCard} [data-invoice-edit]`); await ready('[data-partner-document-dialog] [data-partner-invoice]');
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('[data-partner-line] [name="category"]'), input => input.value)`), ['crafted', 'coin', 'remittance', 'melted']);
  await setRow(0, { weight: '۱۲' });
  await setRow(2, { goldAmount: '۸' });
  await setRow(3, { meltedFee: '۱۲۰۰۰۰۰۰۰' });
  await click('[data-partner-invoice-save]');
  await until(`!document.querySelector('[data-partner-document-dialog]')`);
  const afterEdit = (await workspace()).data;
  const editedEntry = afterEdit.partners[0].entries.find(saved => saved.id === entry.id);
  assert.equal(afterEdit.documents.length, afterMixed.documents.length);
  assert.equal(afterEdit.partners[0].entries.length, afterMixed.partners[0].entries.length);
  assert.equal(editedEntry.transactionId, entry.transactionId);
  assert.equal(editedEntry.invoiceNumber, entry.invoiceNumber);
  assert.deepEqual(editedEntry.documentIds, entry.documentIds);
  assert.equal(editedEntry.lines[0].scaleWeight, 12);
  assert.equal(editedEntry.lines[2].goldAmount, 8);
  assert.equal(editedEntry.lines[3].meltedFee, 120000000);
  assert.ok(Math.abs(editedEntry.lines[3].amount - 120000000 / 4.3318 * 20) < 0.01);
  assert.equal(editedEntry.goldDebit, round(12 + 120000000 / 4.3318 * 20 / 20000000));
  assert.equal(editedEntry.goldCredit, 8.02);
  assert.equal(afterEdit.partners[0].goldBalance, round(beforeMixed.partners[0].goldBalance + editedEntry.goldDebit - editedEntry.goldCredit));
  await go('/account'); await ready('.workspace-page');
  assert.deepEqual((await workspace()).data.partners[0].entries.find(saved => saved.id === entry.id), editedEntry);

  // A document made only of remittances belongs in the document list without stock rows.
  await open('partner-crafted-purchase');
  await fill('[data-partner-invoice] [name="gold18Price"]', '20000000');
  await setRow(0, { category: 'remittance', remittanceDirection: 'credit', goldAmount: '۳', reference: 'سند فقط حواله' });
  await click('[data-partner-invoice-save]'); await success();
  const remittanceOnly = (await workspace()).data;
  const remitEntry = remittanceOnly.partners[0].entries.at(-1);
  assert.equal(remittanceOnly.documents.length, afterEdit.documents.length);
  assert.equal(remitEntry.documentIds.length, 0);
  assert.equal(remittanceOnly.partners[0].goldBalance, round(afterEdit.partners[0].goldBalance - 3));
  await click('[data-section="reports"]'); await click('[data-tool="search"]');
  const remitCard = `[data-invoice-id="${remitEntry.transactionId}"]`;
  await ready(remitCard);
  await click(`${remitCard} [data-invoice-view]`); await ready('[data-partner-document-dialog]');
  assert.equal(await evaluate(`document.querySelector('[data-partner-document-dialog]').textContent.includes('سند فقط حواله')`), true);
  await click('[data-partner-document-close]');

  // The dedicated remittance form also creates a numbered, editable document.
  const standalone = standaloneRemittances[0];
  const standaloneCard = `[data-invoice-id="${standalone.transactionId}"]`;
  await ready(standaloneCard);
  await click(`${standaloneCard} [data-invoice-view]`);
  await ready('[data-partner-document-dialog] [data-partner-remittance-details]');
  assert.equal(await evaluate(`document.querySelector('[data-partner-remittance-details]').textContent.includes('حواله debit')`), true);
  await ready('[data-partner-document-dialog] [data-invoice-print]');
  await click('[data-partner-document-close]');
  await click(`${standaloneCard} [data-invoice-edit]`);
  await ready('[data-partner-document-dialog] [data-partner-settlement-form]');
  const standaloneForm = '[data-partner-document-dialog] [data-partner-settlement-form]';
  assert.equal(await evaluate(`document.querySelector('${standaloneForm} [name="direction"]').value`), 'debit');
  assert.equal(await evaluate(`document.querySelector('${standaloneForm} [name="goldAmount"]').value`), '10');
  for (const [name, value] of Object.entries({ direction: 'credit', goldAmount: '۴', tomanAmount: '۲۵۰۰۰۰', reference: 'حواله مستقل ویرایش‌شده', note: 'اصلاح مقدار و جهت حواله مستقل' })) {
    await fill(`${standaloneForm} [name="${name}"]`, value);
  }
  await click('[data-partner-document-dialog] [data-partner-payment-save]');
  await until(`!document.querySelector('[data-partner-document-dialog]')`);
  const afterStandaloneEdit = (await workspace()).data;
  const standaloneEdited = afterStandaloneEdit.partners[0].entries.find(saved => saved.id === standalone.id);
  assert.equal(afterStandaloneEdit.partners[0].entries.length, remittanceOnly.partners[0].entries.length);
  assert.equal(standaloneEdited.invoiceNumber, standalone.invoiceNumber);
  assert.equal(standaloneEdited.transactionId, standalone.transactionId);
  assert.equal(standaloneEdited.createdAt, standalone.createdAt);
  assert.equal(standaloneEdited.paymentMethod, 'remittance');
  assert.equal(standaloneEdited.goldDebit, 0);
  assert.equal(standaloneEdited.goldCredit, 4);
  assert.equal(standaloneEdited.tomanDebit, 0);
  assert.equal(standaloneEdited.tomanCredit, 250000);
  assert.equal(standaloneEdited.reference, 'حواله مستقل ویرایش‌شده');
  assert.equal(standaloneEdited.note, 'اصلاح مقدار و جهت حواله مستقل');
  assert.equal(afterStandaloneEdit.partners[0].goldBalance, round(remittanceOnly.partners[0].goldBalance - 14));
  assert.equal(afterStandaloneEdit.partners[0].tomanBalance, remittanceOnly.partners[0].tomanBalance - 250000);
  assert.deepEqual(afterStandaloneEdit.documents, remittanceOnly.documents);
  await go('/account'); await ready('.workspace-page');
  assert.deepEqual((await workspace()).data.partners[0].entries.find(saved => saved.id === standalone.id), standaloneEdited);
  await click('[data-section="reports"]'); await click('[data-tool="search"]');
  await fill('.search-controls input', 'حواله مستقل ویرایش‌شده');
  await ready(standaloneCard);
  assert.equal(await evaluate(`document.querySelectorAll('[data-invoice-id]').length`), 1);
  await click(`${standaloneCard} [data-invoice-view]`);
  await ready('[data-partner-document-dialog] [data-partner-remittance-details]');
  assert.equal(await evaluate(`document.querySelector('[data-partner-document-dialog]').textContent.includes('اصلاح مقدار و جهت حواله مستقل')`), true);
  await resize(390, 844);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), true);
  await screenshot('partner-standalone-remittance-document-mobile', '[data-partner-document-dialog]');
  await click('[data-partner-document-close]'); await resize(1440);
  console.log('Partner browser checks passed: numbered standalone remittance view/edit/reload/search, separate drafts, purchases, stock-linked sales, independent melted fee rates, mixed invoice draft/save/reload/edit, linked inventory, balances, remittance-only document and mobile.');
}
